import { FlaskConical, Sparkles } from "lucide-react";
import type { AiSource } from "@shared/schema";
import { cn } from "@/lib/utils";

/** Tells the user whether an answer is live AI or sample data. */
export function AiSourceBadge({ source, className }: { source: AiSource; className?: string }) {
  const mock = source === "mock";
  return (
    <span
      title={mock ? "Sample data. Live AI turns on when a Gemini API key is configured." : "Generated by Google Gemini"}
      className={cn(
        "inline-flex items-center gap-1.5 rounded-full border px-2.5 py-0.5 text-xs font-medium",
        mock ? "border-amber-300/60 bg-amber-50 text-amber-800 dark:border-amber-500/30 dark:bg-amber-500/10 dark:text-amber-200" : "bg-accent text-accent-foreground",
        className,
      )}
    >
      {mock ? <FlaskConical className="h-3 w-3" /> : <Sparkles className="h-3 w-3" />}
      {mock ? "Sample data" : "AI generated"}
    </span>
  );
}
